#!/usr/bin/env python3
"""Render a mosquitto ACL file from devices.csv + acl.tmpl (§S12).

Usage: render_acl.py devices.csv acl.tmpl > edge-parking.acl

devices.csv columns: username,role[,password]  (password column ignored here).
acl.tmpl is grouped by `# role=<name>` marker lines; each user's block is the
topic lines of their role, preceded by `user <username>`.
"""
import csv
import sys


def load_roles(tmpl_path):
    roles, current = {}, None
    with open(tmpl_path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("# role="):
                current = line.split("=", 1)[1].split("：", 1)[0].strip()
                roles[current] = []
            elif current and line.strip():
                roles[current].append(line)
    return roles


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    roles = load_roles(sys.argv[2])
    out = ["# Generated by render_acl.py — do not edit (regenerate from devices.csv)"]
    with open(sys.argv[1], encoding="utf-8") as f:
        for row in csv.reader(f):
            if not row or row[0].strip().startswith("#"):
                continue
            user, role = row[0].strip(), row[1].strip()
            if role not in roles:
                sys.exit(f"unknown role {role!r} for user {user!r}")
            out.append(f"user {user}")
            out.extend(roles[role])
    print("\n".join(out))


if __name__ == "__main__":
    main()
